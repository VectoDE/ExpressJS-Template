const fs = require('node:fs');
const path = require('node:path');
const ejs = require('ejs');
// espree is ESLint's parser and comes with the ESLint dev dependency; it is only used at build time.
const espree = require('espree');
const globals = require('globals');

/**
 * Turns every EJS view into a plain JavaScript function at build time. Cloudflare Workers forbid eval and
 * `new Function`, which EJS needs to compile templates at run time, and the bundle is an ES module (strict mode),
 * which rules out the `with (locals)` block EJS normally wraps around a template. Instead each function starts
 * with `var name = locals.name` for every free identifier the template uses. Names that are JavaScript
 * built-ins (Math, JSON, encodeURIComponent, ...) are left alone, so they still resolve to the globals.
 */

// Names EJS itself defines inside the generated function, plus the function's own parameters.
const EJS_INTERNALS = new Set(['__output', '__append', '__line', '__lines', '__filename', '__locals']);
const PARAMETERS = new Set(['locals', 'escapeFn', 'include', 'rethrow']);
const BUILT_INS = new Set([...Object.keys(globals.builtin), 'undefined', 'NaN', 'Infinity', 'arguments']);

const listViews = (dir, base = dir) =>
  fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return listViews(full, base);
      return entry.name.endsWith('.ejs') ? [path.relative(base, full)] : [];
    })
    .sort((a, b) => a.localeCompare(b));

// Template key: path below the views directory, forward slashes, without extension ("pages/auth/login").
const keyOf = (relative) =>
  relative
    .split(path.sep)
    .join('/')
    .replace(/\.ejs$/, '');

// Every identifier that is read as a variable: not a property after "." or "?.", not a keyword.
const freeIdentifiers = (source) => {
  const tokens = espree.tokenize(source, { ecmaVersion: 'latest', sourceType: 'script' });
  const names = new Set();
  tokens.forEach((token, index) => {
    if (token.type !== 'Identifier') return;
    const previous = tokens[index - 1];
    if (previous?.type === 'Punctuator' && (previous.value === '.' || previous.value === '?.')) return;
    if (EJS_INTERNALS.has(token.value) || PARAMETERS.has(token.value) || BUILT_INS.has(token.value)) return;
    names.add(token.value);
  });
  return [...names].sort((a, b) => a.localeCompare(b));
};

const compileView = (text, filename) => {
  const template = new ejs.Template(text, { filename, _with: false, compileDebug: false, localsName: 'locals' });
  // Builds template.source; the function EJS creates on the way is thrown away.
  template.compile();
  const body = template.source;
  const names = freeIdentifiers(body);
  const assignments = names.map((name) => `${name} = locals.${name}`).join(',\n    ');
  const declarations = names.length ? `  var ${assignments};\n` : '';
  // The template body sits in its own block, so its own let/const declarations may reuse a local's name.
  return `function (locals, escapeFn, include) {\n${declarations}  {\n${body}  }\n}`;
};

// Source of a CommonJS module that exports { "<key>": function, ... } for every view below viewsDir.
const precompileViews = (viewsDir) => {
  const entries = listViews(viewsDir).map((relative) => {
    const filename = path.join(viewsDir, relative);
    const text = fs.readFileSync(filename, 'utf8');
    return `  ${JSON.stringify(keyOf(relative))}: ${compileView(text, filename)}`;
  });
  return [
    '// Generated by scripts/build-worker.js from src/views. Do not edit.',
    "'use strict';",
    '',
    `module.exports = {\n${entries.join(',\n')}\n};`,
    '',
  ].join('\n');
};

module.exports = { precompileViews, compileView, freeIdentifiers, listViews, keyOf };
