const knexFactory = require('knex');
const migrations = require('../src/db/migrations');

/**
 * D1 applies its schema with `wrangler d1 migrations apply` from plain SQL files (worker/migrations). This turns
 * the Knex migrations of the app into those files, so both schemas come from one source: each migration runs
 * against an empty in-memory SQLite database and the SQL it sends is recorded. D1 is SQLite, so the statements
 * are the ones the SQLite dialect of the app would run.
 */
const HEADER = (name) =>
  [
    '-- SPDX-FileCopyrightText: 2024-2026 VectoDE',
    '-- SPDX-License-Identifier: MIT',
    `-- Generated by scripts/build-worker.js from src/db/migrations (${name}). Do not edit.`,
    '',
  ].join('\n');

const fileNameOf = (index, name) => `${String(index + 1).padStart(4, '0')}_${name.replace(/^\d+_/, '')}.sql`;

const generateMigrationSql = async () => {
  const knex = knexFactory({ client: 'better-sqlite3', connection: { filename: ':memory:' }, useNullAsDefault: true });
  const files = [];
  try {
    const list = await migrations.getMigrations();
    for (const [index, migration] of list.entries()) {
      const statements = [];
      const record = (query) => {
        // DDL carries its values inline; bound values, if a migration ever uses them, are inlined the Knex way.
        statements.push(query.bindings?.length ? knex.raw(query.sql, query.bindings).toString() : query.sql);
      };
      knex.on('query', record);
      // Migrations build on each other, so they run in order on the same database.
      await migration.up(knex);
      knex.off('query', record);
      const name = migrations.getMigrationName(migration);
      const body = statements
        .filter((statement) => !/^\s*(pragma|select)\b/i.test(statement))
        .map((statement) => `${statement};`)
        .join('\n');
      files.push({ name: fileNameOf(index, name), sql: `${HEADER(name)}${body}\n` });
    }
  } finally {
    await knex.destroy();
  }
  return files;
};

module.exports = { generateMigrationSql };
