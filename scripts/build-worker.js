/**
 * Prepares the public demo for Cloudflare Workers (`npm run build:worker`, then `npx wrangler deploy`):
 *   worker-dist/views.js        every EJS view as a precompiled function (Workers forbid eval)
 *   worker-dist/openapi.json    the API description, made by swagger-jsdoc here instead of at run time
 *   worker-dist/demo-seed.js    the demo accounts with password hashes, for the hourly reset
 *   worker-dist/seed.sql        the same accounts as SQL, for the first `wrangler d1 execute`
 *   worker-dist/assets/         static files served by Workers Static Assets, with _headers
 *   worker/migrations/*.sql     the D1 schema, generated from src/db/migrations
 * `--check` only verifies that worker/migrations matches the Knex migrations and changes nothing.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'worker-dist');
const MIGRATIONS_DIR = path.join(ROOT, 'worker', 'migrations');
const WRANGLER_CONFIG = path.join(ROOT, 'wrangler.jsonc');

// The demo hashes with the cost the Worker runs with, so the seeded accounts need no rehash at sign-in.
const hashCostFromWrangler = () => {
  const match = /"PASSWORD_HASH_COST"\s*:\s*"(\d+)"/.exec(fs.readFileSync(WRANGLER_CONFIG, 'utf8'));
  if (!match) throw new Error('wrangler.jsonc has no vars.PASSWORD_HASH_COST');
  return match[1];
};

// The build runs with the demo settings, not with whatever .env holds; nothing here touches a real database.
Object.assign(process.env, {
  NODE_ENV: 'development',
  DEMO_MODE: 'true',
  PASSWORD_HASH_COST: hashCostFromWrangler(),
  DATABASE_URL: 'sqlite::memory:',
  API_DOCS_ENABLED: 'true',
  LOG_LEVEL: 'warn',
});

const { generateMigrationSql } = require('../worker/d1-migrations');

const write = (file, content) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
};

const migrationsUpToDate = async () => {
  const expected = await generateMigrationSql();
  const present = fs.existsSync(MIGRATIONS_DIR) ? fs.readdirSync(MIGRATIONS_DIR).filter((f) => f.endsWith('.sql')) : [];
  const differences = expected
    .filter(
      ({ name, sql }) => !present.includes(name) || fs.readFileSync(path.join(MIGRATIONS_DIR, name), 'utf8') !== sql
    )
    .map(({ name }) => name);
  const extra = present.filter((name) => !expected.some((file) => file.name === name));
  return { expected, differences: [...differences, ...extra] };
};

const writeMigrations = (expected) => {
  expected.forEach(({ name, sql }) => write(path.join(MIGRATIONS_DIR, name), sql));
};

const copyDir = (from, to, filter = () => true) => {
  fs.mkdirSync(to, { recursive: true });
  fs.readdirSync(from, { withFileTypes: true }).forEach((entry) => {
    const source = path.join(from, entry.name);
    const target = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(source, target, filter);
    else if (filter(entry.name)) fs.copyFileSync(source, target);
  });
};

// Same headers helmet sets on these files in the Node app (src/app.js, src/docs/swagger.js).
const COMMON_HEADERS = [
  'Strict-Transport-Security: max-age=63072000; includeSubDomains; preload',
  'X-Content-Type-Options: nosniff',
  'X-Frame-Options: DENY',
  'Referrer-Policy: no-referrer',
  'Cross-Origin-Opener-Policy: same-origin',
  'Cross-Origin-Resource-Policy: same-origin',
  'Cross-Origin-Embedder-Policy: require-corp',
  'Origin-Agent-Cluster: ?1',
  'X-DNS-Prefetch-Control: off',
  'X-Download-Options: noopen',
  'X-Permitted-Cross-Domain-Policies: none',
  'X-XSS-Protection: 0',
  'Permissions-Policy: accelerometer=(), camera=(), display-capture=(), geolocation=(), gyroscope=(), ' +
    'magnetometer=(), microphone=(), payment=(), usb=(), browsing-topics=()',
];
const APP_CSP =
  "default-src 'self'; base-uri 'none'; script-src 'self'; script-src-attr 'none'; style-src 'self'; " +
  "img-src 'self'; font-src 'self'; connect-src 'self'; manifest-src 'self'; media-src 'none'; " +
  "worker-src 'none'; form-action 'self'; frame-ancestors 'none'; object-src 'none'; upgrade-insecure-requests";
const DOCS_CSP =
  "default-src 'self'; base-uri 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; " +
  "img-src 'self' data:; connect-src 'self'; form-action 'self'; frame-ancestors 'none'; object-src 'none'";

const headersFile = () =>
  [
    '# Generated by scripts/build-worker.js. Security headers for files served by Workers Static Assets.',
    '/assets/*',
    ...[...COMMON_HEADERS, `Content-Security-Policy: ${APP_CSP}`, 'Cache-Control: public, max-age=604800'].map(
      (line) => `  ${line}`
    ),
    '/docs/*',
    ...[...COMMON_HEADERS, `Content-Security-Policy: ${DOCS_CSP}`, 'Cache-Control: public, max-age=86400'].map(
      (line) => `  ${line}`
    ),
    '',
  ].join('\n');

// Swagger UI files the /docs page loads; its index.html is left out so the app keeps answering /docs/.
const SWAGGER_FILES = [
  'swagger-ui.css',
  'swagger-ui-bundle.js',
  'swagger-ui-standalone-preset.js',
  'favicon-16x16.png',
  'favicon-32x32.png',
];

const buildAssets = () => {
  const assets = path.join(OUT, 'assets');
  copyDir(path.join(ROOT, 'src', 'public'), path.join(assets, 'assets'));
  const swaggerDist = path.dirname(require.resolve('swagger-ui-dist/package.json'));
  SWAGGER_FILES.forEach((file) => {
    write(path.join(assets, 'docs', file), fs.readFileSync(path.join(swaggerDist, file)));
  });
  write(path.join(assets, '_headers'), headersFile());
};

const buildSeed = async () => {
  const knexFactory = require('knex');
  const { hashPassword } = require('../src/utils/password');
  const { DEMO_ACCOUNTS } = require('../worker/demo-accounts');
  const { userRecordOf } = require('../worker/demo');
  const seed = await Promise.all(
    DEMO_ACCOUNTS.map(async ({ password, ...account }) => ({ ...account, passwordHash: await hashPassword(password) }))
  );
  write(
    path.join(OUT, 'demo-seed.js'),
    `// Generated by scripts/build-worker.js from worker/demo-accounts.js. Do not edit.\nmodule.exports = ${JSON.stringify(seed, null, 2)};\n`
  );
  // SQL for the first fill of an empty D1 database; the Cron Trigger restores the same rows every hour.
  const knex = knexFactory({ client: 'better-sqlite3', useNullAsDefault: true });
  const at = Date.now();
  const rows = seed.map((account) => {
    const user = userRecordOf(account, new Date(at));
    return {
      id: user.id,
      name: user.name,
      email: user.email,
      password: user.password,
      role: user.role,
      is_email_verified: 1,
      locale: user.locale,
      credentials_changed_at: at,
      failed_login_attempts: 0,
      lock_until: null,
      two_factor_enabled: 0,
      two_factor_secret: null,
      two_factor_pending_secret: null,
      two_factor_last_used_step: -1,
      two_factor_enabled_at: null,
      created_at: at,
      updated_at: at,
    };
  });
  const statements = [
    ...['passkeys', 'recovery_codes', 'tokens', 'audit_events', 'web_sessions', 'rate_limits', 'users'].map((table) =>
      knex(table).del().toString()
    ),
    knex('users').insert(rows).toString(),
  ];
  const sql = statements.map((statement) => `${statement};`).join('\n');
  write(
    path.join(OUT, 'seed.sql'),
    `-- Generated by scripts/build-worker.js: the demo accounts of worker/demo-accounts.js.\n${sql}\n`
  );
  await knex.destroy();
};

const buildViews = () => {
  const { precompileViews } = require('../worker/precompile-views');
  write(path.join(OUT, 'views.js'), precompileViews(path.join(ROOT, 'src', 'views')));
};

const buildOpenApi = () => {
  const { swaggerSpec } = require('../src/docs/swagger');
  write(path.join(OUT, 'openapi.json'), `${JSON.stringify(swaggerSpec)}\n`);
};

const main = async () => {
  const { expected, differences } = await migrationsUpToDate();
  if (process.argv.includes('--check')) {
    if (differences.length) {
      console.error(`worker/migrations is out of date (${differences.join(', ')}); run npm run build:worker`);
      process.exitCode = 1;
    } else {
      console.log('worker/migrations matches src/db/migrations');
    }
    return;
  }
  if (differences.length) {
    writeMigrations(expected);
    console.log(`Updated worker/migrations: ${differences.join(', ')}`);
  }
  fs.rmSync(OUT, { recursive: true, force: true });
  buildViews();
  buildOpenApi();
  buildAssets();
  await buildSeed();
  console.log('Worker build ready in worker-dist/. Next: npx wrangler deploy (see README, "Live demo on Cloudflare").');
};

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
