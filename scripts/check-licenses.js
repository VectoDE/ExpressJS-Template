/**
 * Checks the licenses of all production dependencies against an allow-list and writes
 * docs/third-party-notices.md with name, version, license and copyright notice of each package.
 *
 *   node scripts/check-licenses.js          check only (CI)
 *   node scripts/check-licenses.js --write  check and regenerate docs/third-party-notices.md
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const ALLOWED = new Set([
  'MIT',
  'MIT-0',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  '0BSD',
  'BlueOak-1.0.0',
  'CC0-1.0',
  'Unlicense',
  'Python-2.0',
]);

const lock = JSON.parse(fs.readFileSync(path.join(ROOT, 'package-lock.json'), 'utf8'));
const packages = Object.entries(lock.packages)
  .filter(([location, meta]) => location.startsWith('node_modules/') && !meta.dev)
  .map(([location, meta]) => ({
    location,
    name: location.slice(location.lastIndexOf('node_modules/') + 'node_modules/'.length),
    version: meta.version,
  }));

const licenseOf = (dir) => {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const raw = pkg.license || (pkg.licenses || []).map((l) => l.type).join(' OR ') || 'UNKNOWN';
  return typeof raw === 'string' ? raw : raw.type;
};

const isAllowed = (expression) =>
  expression
    .replaceAll(/[()]/g, '')
    .split(' OR ')
    .some((option) => option.split(' AND ').every((id) => ALLOWED.has(id.trim())));

const noticeOf = (dir) => {
  const file = fs.readdirSync(dir).find((name) => /^(licen[cs]e|copying)(\.|$)/i.test(name));
  if (!file) {
    return '';
  }
  const text = fs.readFileSync(path.join(dir, file), 'utf8');
  return text
    .split('\n')
    .map((line) => line.replace(/^[\s*-]+/, '').trim())
    .filter((line) => /^(copyright\s*(\(c\)|©|\d)|\(c\)\s*\d|©)/i.test(line))
    .slice(0, 3)
    .join('\n');
};

const rows = [];
const problems = [];
for (const { location, name, version } of packages) {
  const dir = path.join(ROOT, location);
  if (!fs.existsSync(path.join(dir, 'package.json'))) {
    continue;
  }
  const license = licenseOf(dir);
  if (!isAllowed(license)) {
    problems.push(`${name}@${version}: ${license}`);
  }
  rows.push({ name, version, license, notice: noticeOf(dir) });
}
rows.sort((a, b) => a.name.localeCompare(b.name));

if (process.argv.includes('--write')) {
  const unique = [...new Map(rows.map((row) => [`${row.name}@${row.version}`, row])).values()];
  const body = [
    '# Third-party notices',
    '',
    'This project ships the following open source packages as runtime dependencies.',
    'Each package keeps its own license; the full texts are in `node_modules/<package>/LICENSE` after `npm ci`.',
    'Generated by `node scripts/check-licenses.js --write`.',
    '',
    '| Package | Version | License | Copyright |',
    '| --- | --- | --- | --- |',
    ...unique.map((r) => {
      const notice = r.notice.replaceAll('|', String.raw`\|`).replaceAll('\n', '<br>');
      return `| ${r.name} | ${r.version} | ${r.license} | ${notice} |`;
    }),
    '',
  ];
  fs.writeFileSync(path.join(ROOT, 'docs', 'third-party-notices.md'), body.join('\n'));
}

if (problems.length) {
  console.error(`License not on the allow-list:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
console.log(`${rows.length} production packages, all licenses allowed.`);
